// Этот файл отвечает за учёт "пропущенных публикаций" — случаев, когда
// запись в Redis не удалась (например, Redis был недоступен долю секунды).
// Счётчик нужен, чтобы видеть проблему как ЧИСЛО (можно поставить алерт
// "если пропусков больше N за минуту — шли в Telegram"), а не только
// как текст в логах, который никто не читает в реальном времени.
package publisher

import "sync/atomic"

// Metrics хранит счётчики состояния publisher, общие на весь процесс.
// Живёт в Publisher (не в WSClient!) специально: реконнект к бирже
// (WS) и реконнект к Redis — независимые друг от друга вещи, поэтому
// счётчик пропущенных публикаций не должен обнуляться при реконнекте
// WS-соединения с Gate.io.
type Metrics struct {
	// dropped — сколько раз подряд с момента старта процесса не удалось
	// опубликовать данные в Redis (любой Publish* метод вернул ошибку).
	//
	// Тип atomic.Int64 (а не обычный int64 + sync.Mutex) выбран потому,
	// что счётчик инкрементируется из горутины ReadLoop, а читается
	// из горутины RunPingLoop раз в 10 секунд — это классический случай
	// "один пишет часто, другой читает редко", для которого atomic
	// проще и быстрее ручной блокировки мьютексом.
	dropped atomic.Int64
}

// NewMetrics создаёт пустой счётчик (все значения — 0).
func NewMetrics() *Metrics {
	return &Metrics{}
}

// IncDropped увеличивает счётчик пропущенных публикаций на 1.
// Вызывается из parser.go в каждом месте, где Publish* метод вернул ошибку.
func (m *Metrics) IncDropped() {
	m.dropped.Add(1)
}

// Dropped возвращает текущее значение счётчика (сколько публикаций
// пропущено с момента старта процесса).
func (m *Metrics) Dropped() int64 {
	return m.dropped.Load()
}
