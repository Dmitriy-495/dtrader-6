// Пакет indicator содержит ЧИСТУЮ математику технического анализа.
// Ни один файл здесь не знает о Redis, JSON или сети — только числа на
// входе и числа на выходе. Это осознанное разделение: reader/ достаёт
// сырые данные и превращает их в []float64 (цены, объёмы), а indicator/
// считает индикаторы над этими срезами. Такое разделение позволяет
// тестировать индикаторы юнит-тестами на простых массивах чисел, без
// поднятия Redis и без сети вообще.
package indicator

// EMA — экспоненциальная скользящая средняя (Exponential Moving Average).
//
// В отличие от простой скользящей средней (SMA), EMA даёт больший вес
// последним значениям — реагирует на изменения быстрее, но остаётся
// куда более гладкой, чем сырая цена. Это делает её основным строительным
// блоком индикатора тренда T на всех таймфреймах (1m/8m/24m).
//
// period — период EMA (например 12, 24, 72). Чем больше период, тем
// "медленнее" и более сглаженная получается линия.
//
// prices — цены в хронологическом порядке (старые → новые). Обычно это
// цены закрытия свечей (Close), но функция не делает предположений о
// происхождении данных — только считает по числам.
//
// Возвращает 0, если prices пуст (пустой срез не может дать значение
// индикатора) — вызывающий код (trend.go) должен считать 0 сигналом
// "данных ещё недостаточно", а не настоящим значением EMA.
func EMA(prices []float64, period int) float64 {
	if len(prices) == 0 || period <= 0 {
		return 0
	}

	// Коэффициент сглаживания α = 2/(period+1).
	// Тот же принцип, что уже используется в bot для EMA латентности
	// ping-pong (bot/internal/gateway/pingloop.go, α = 2/(100+1)) —
	// сохраняем единый математический подход во всём проекте.
	alpha := 2.0 / (float64(period) + 1.0)

	// Инициализация первым значением серии — так же, как в pingloop.go
	// (комментарий "emaLat == 0 → emaLat = current"). Это стандартная,
	// широко принятая практика: альтернатива (инициализация нулём или
	// SMA за первые period значений) даёт похожий результат при
	// достаточной длине серии, но так проще и предсказуемее.
	ema := prices[0]
	for i := 1; i < len(prices); i++ {
		ema = prices[i]*alpha + ema*(1-alpha)
	}
	return ema
}

// EMASeries считает EMA на каждом шаге серии и возвращает срез той же
// длины, что и prices — то есть "как менялась EMA со временем", а не
// только финальное значение. Нужно для индикаторов, которым важна
// ДИНАМИКА EMA (например MACD — разность двух EMA-серий на каждом шаге),
// а не только текущее значение.
func EMASeries(prices []float64, period int) []float64 {
	if len(prices) == 0 || period <= 0 {
		return nil
	}
	alpha := 2.0 / (float64(period) + 1.0)
	out := make([]float64, len(prices))
	out[0] = prices[0]
	for i := 1; i < len(prices); i++ {
		out[i] = prices[i]*alpha + out[i-1]*(1-alpha)
	}
	return out
}
